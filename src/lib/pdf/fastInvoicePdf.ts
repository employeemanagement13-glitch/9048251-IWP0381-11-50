import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export function createInvoiceJsPdf(
  data: Array<Record<string, unknown>>,
  filename: string
): jsPDF {
  const doc = new jsPDF({
    orientation: "landscape",
    unit: "pt",
    format: "a4",
  });

  const rawHeaders = data.length > 0 ? Object.keys(data[0]) : [];
  const headers = rawHeaders.length > 0 ? ["#", ...rawHeaders] : [];

  const body = data.map((row, idx) => {
    return [
      `${idx + 1}.`,
      ...rawHeaders.map((h) => {
        const val = row[h];
        if (val === null || val === undefined || val === "") return "—";
        if (typeof val === "number") return val.toLocaleString();
        return String(val);
      }),
    ];
  });

  const columnStyles: Record<number, any> = {
    0: { cellWidth: 24, halign: "center", fontStyle: "bold", textColor: [100, 116, 139] },
    1: { cellWidth: 46, fontStyle: "bold" },
    2: { cellWidth: 36 },
    3: { cellWidth: 70 },
    4: { cellWidth: 42 },
    5: { cellWidth: 42 },
    6: { cellWidth: 35 },
    7: { cellWidth: 50 },
    8: { cellWidth: 50 },
    9: { cellWidth: 30 },
    10: { cellWidth: 30, halign: "right" },
    11: { cellWidth: 46, halign: "right", fontStyle: "bold" },
    12: { cellWidth: 35 },
    13: { cellWidth: 40, halign: "right" },
    14: { cellWidth: 40, halign: "right" },
    15: { cellWidth: 35, halign: "right" },
    16: { cellWidth: 35, halign: "right" },
    17: { cellWidth: "auto" },
  };

  const now = new Date();
  const nowStr = `${now.toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  })} ${now.toLocaleTimeString("en-US", {
    hour: "2-digit",
    minute: "2-digit",
    hour12: true,
  })}`;

  autoTable(doc, {
    head: [headers],
    body: body,
    startY: 42,
    margin: { top: 45, left: 15, right: 15, bottom: 25 },
    styles: {
      fontSize: 6,
      cellPadding: 2.5,
      overflow: "linebreak",
      lineColor: [243, 244, 246],
      lineWidth: 0.5,
      textColor: [31, 41, 55],
    },
    headStyles: {
      fillColor: [229, 30, 42],
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 6.5,
      halign: "left",
      cellPadding: 3,
    },
    alternateRowStyles: {
      fillColor: [254, 242, 242],
    },
    columnStyles: columnStyles,
    didDrawPage: (dataHook) => {
      // Header
      doc.setFontSize(11);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(185, 28, 28);
      doc.text(filename, 15, 20);

      doc.setFontSize(7.5);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(107, 114, 128);
      doc.text("Generated by Distroline DMS", 15, 30);

      const totalStr = `Total Records: ${data.length}`;
      doc.setFontSize(8.5);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(17, 24, 39);
      doc.text(totalStr, doc.internal.pageSize.width - 15, 20, { align: "right" });

      doc.setFontSize(7.5);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(75, 85, 99);
      doc.text(nowStr, doc.internal.pageSize.width - 15, 30, { align: "right" });

      // Header red accent line
      doc.setDrawColor(254, 202, 202);
      doc.setLineWidth(0.75);
      doc.line(15, 35, doc.internal.pageSize.width - 15, 35);

      // Footer
      const pageNumber = dataHook.pageNumber;
      const totalPages = (doc as any).internal.pages.length - 1;
      doc.setFontSize(7);
      doc.setTextColor(156, 163, 175);
      doc.text(`Generated by Distroline DMS • ${nowStr}`, 15, doc.internal.pageSize.height - 10);
      doc.text(`Page ${pageNumber} of ${totalPages}`, doc.internal.pageSize.width - 15, doc.internal.pageSize.height - 10, { align: "right" });
    },
  });

  return doc;
}

export function generateFastInvoicesPdfBlob(
  data: Array<Record<string, unknown>>,
  filename: string
): Blob {
  const doc = createInvoiceJsPdf(data, filename);
  return doc.output("blob");
}

export function generateFastInvoicesPdfBuffer(
  data: Array<Record<string, unknown>>,
  filename: string
): ArrayBuffer {
  const doc = createInvoiceJsPdf(data, filename);
  return doc.output("arraybuffer");
}
